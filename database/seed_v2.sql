SELECT m.category,
       m.total_sales,
       t.target_amount,
       ROUND(m.total_sales / t.target_amount * 100, 2) AS completion_pct
FROM monthly_sales m
JOIN category_target t
  ON m.year=t.year AND m.month=t.month AND m.category=t.category
WHERE m.year='2026' AND m.month=8
ORDER BY completion_pct DESC;
